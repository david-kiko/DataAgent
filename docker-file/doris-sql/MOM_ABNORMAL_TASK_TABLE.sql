  `CFACTORY_NAME` varchar(256) NULL COMMENT "工厂名称",
  `CBIZ_ORG_ID` bigint NULL COMMENT "工厂组织ID",
  `CBIZ_ORG_NAME` varchar(256) NULL COMMENT "工厂组织名称",

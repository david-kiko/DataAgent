insert into bi.`MOM_ABNORMAL_TASK`  
select t1.`CID`
  , t1.`CREMARK`
  , t1.`CSOFT_DELETE_FLAG`
  , t1.`CCREATOR_ID`
  , t1.`CCREATOR_ENTITY_TYPE`
  , t1.`CPROMISE_RESOLUTION_TIME`
  , t1.`CHANDLER_ENTITY_TYPE`
  , t1.`CFACTORY_ENTITY_TYPE`
  , t1.`CQEQUIP_ENTITY_TYPE`
  , t1.`CCLOSE_TIME`
  , t1.`CCREATE_TIME`
  , t1.`CABNORMAL_DESC`
  , t1.`CCODE`
  , t1.`CLATEST_UPDATE_TIME`
  , t1.`CMODIFIER_ID`
  , t1.`CENTITY_TYPE`
  , t1.`CPROCESS_MEASURES`
  , t1.`CABNORMAL_CATEGORY_ID`
  , t1.`CABNORMAL_CATEGORY_ENTITY_TYPE`
  , t1.`CENV`
  , t1.`CCLOSER_ID`
  , t1.`CREQUIRED_FINISH_TIME`
  , t1.`CQEQUIP_ID`
  , t1.`CABNORMAL_CAUSE`
  , t1.`CHANDLER_ID`
  , t1.`CSECURITY_LEVEL`
  , t1.`CINITIATOR_ENTITY_TYPE`
  , t1.`CJOIN_FLOW_FLAG`
  , t1.`CNAME`
  , t1.`CPROCESS_INSTANCE_ID`
  , t1.`CFACTORY_ID`
  , t4.`CNAME` as `CFACTORY_NAME`
  , t1.`CBIZ_ORG_ID`
  , t3.`CNAME` as `CBIZ_ORG_NAME`
  , t1.`CEQUIP_ID`
  , t1.`CBIZ_ORG_ENTITY_TYPE`
  , t1.`CLIFECYCLE_STATE`
  , t1.`CLIFECYCLE_TEMPLATE`
  , t1.`CEQUIP_ENTITY_TYPE`
  , t1.`CPROCESS_KEY`
  , t1.`CUSERID`
  , t1.`CLIFECYCLE_STATE_TYPE`
  , t1.`CINITIATOR_ID`
  , t1.`CCLOSER_ENTITY_TYPE`
  , t1.`CMODIFIER_ENTITY_TYPE`
  , t1.`CCLOSURE_EXPLANATION`
  , t2.CPROCESS_TIME
  , t2.CINITIATE_TIME
  , t2.CCLOSE_TIME
from target.`MOM_ABNORMAL_TASK` t1
INNER JOIN (SELECT CSOURCE_ID AS CID,
MIN(CASE COPERATION_TYPE WHEN 'PROCESS' THEN COPERATION_TIME END) as CPROCESS_TIME,
MAX(CASE COPERATION_TYPE WHEN 'INITIATE' THEN COPERATION_TIME END) as CINITIATE_TIME,
MAX(CASE COPERATION_TYPE WHEN 'CLOSE' THEN COPERATION_TIME END) as CCLOSE_TIME
FROM target.MOM_ABNORMAL_TASK_LOG_LINK
GROUP by CSOURCE_ID) t2
ON t1.CID = t2.CID
LEFT JOIN target.SYS_BIZ_ORG t3 ON t1.CBIZ_ORG_ID = t3.CID
LEFT JOIN target.SYS_BIZ_ORG t4 ON t1.CFACTORY_ID = t4.CID
where t1.CSOFT_DELETE_FLAG=0
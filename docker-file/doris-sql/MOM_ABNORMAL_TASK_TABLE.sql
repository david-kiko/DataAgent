  `CBIZ_ORG_ENTITY_TYPE` varchar(256) NULL,
  `CLIFECYCLE_STATE` varchar(256) NULL COMMENT "异常状态 [APT_PROCESSED:已处理, APT_PROCESSING:处理中, APT_PENDING:待处理, APT_CLOSED:已关闭]",
  `CLIFECYCLE_TEMPLATE` varchar(256) NULL COMMENT "生命周期模板",

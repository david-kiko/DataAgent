  `CHANDLER_ID` bigint NULL COMMENT "处理人	ID",
  `CSECURITY_LEVEL` varchar(256) NULL COMMENT "密级",
  `CINITIATOR_ENTITY_TYPE` varchar(256) NULL,
  `CJOIN_FLOW_FLAG` varchar(1) NULL COMMENT "是否加入审批流",
  `CNAME` varchar(512) NULL COMMENT "名称",
  `CPROCESS_INSTANCE_ID` varchar(256) NULL COMMENT "所属流程",

  ,t1.CSPECIFIED_PLANNED_START_TIME
  ,t1.CCONTROL_STATUS
  ,t1.CMANU_TYPE
  ,t1.CSERIAL_NUMBER_FLAG
  ,t1.CSECURITY_LEVEL
  ,t1.CPROD_ORDER_ID
  ,t1.CNAME
  ,t1.CROUTING_ID
  ,t1.CUNIT
  ,t1.CREMARK
  ,t1.CMODIFIER_ID
  ,t1.CMODIFIER_ENTITY_TYPE
  ,t1.CLATEST_UPDATE_TIME
  ,t1.CBIZ_ORG_ENTITY_TYPE
from target.MOM_MANU_ORDER t1 
